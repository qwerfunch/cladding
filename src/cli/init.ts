/** Optional project metadata for the spec.yaml seed (F-3a5339, v0.3.49). */
interface SpecSeedMetadata {
  /** One-line summary of the project. Falls back to intent if not provided. */
  readonly description?: string;
  /** Starting project version. Default '0.0.1'. */
  readonly version?: string;
  /** Source-repository URL. Empty placeholder line when not provided. */
  readonly repository?: string;
  /** TL;DR of project-context.md. Falls back to intent if not provided. */
  readonly intent_summary?: string;
  /**
   * AI behavior hints inferred by onboarding (or hand-authored).
   * Renders as a nested `ai_hints:` block under `project:`. v0.3.57+ (F-00eb1a).
   */
  readonly ai_hints?: {
    readonly preferred_persona?: string;
    readonly token_budget_per_session?: number;
    readonly test_framework?: string;
    readonly primary_branch?: string;
    readonly forbidden_patterns?: readonly string[];
    /** Advisory preferred-pattern triples. v0.3.58+ (F-32b1e0). */
    readonly preferred_patterns?: readonly {
      readonly when: string;
      readonly prefer: string;
      readonly over?: string;
    }[];
  };
}

function quoted(value: string): string {
  return `"${value.replace(/"/g, '\\"')}"`;
}

/** Collapses an intent string to a single short line (≤ 120 chars). */
function oneLine(text: string): string {
  const collapsed = text.replace(/\s+/g, ' ').trim();
  return collapsed.length > 120 ? `${collapsed.slice(0, 117)}…` : collapsed;
}

function hasAnyAiHint(h: NonNullable<SpecSeedMetadata['ai_hints']>): boolean {
  return Boolean(
    h.preferred_persona ||
      typeof h.token_budget_per_session === 'number' ||
      h.test_framework ||
      h.primary_branch ||
      (h.forbidden_patterns && h.forbidden_patterns.length > 0) ||
      (h.preferred_patterns && h.preferred_patterns.length > 0),
  );
}

// v0.3.49 (F-99c6e5) — `specSeed` emits `features: []` so the sharded
// layout activates from day one. Every spec-gated detector
// (MISSING_IMPLEMENTATION, AC_DRIFT, UNTESTED_AC, …) reads
// `spec/features/<slug>-<hash6>.yaml` shards directly.
//
// v0.4.0 — no placeholder shard is written at init time. External users
// receive a clean spec; the AI (or `clad_create_feature` / the `clad` CLI)
// registers real features on demand using the hash-based filename model.
// The legacy `F-NNN` sequential format is reserved for cladding's own
// historical features and is never produced for external users.
//
// v0.3.49 (F-3a5339) — Project also accepts optional metadata (description,
// version, repository, intent_summary). When the intent path is taken,
// description + intent_summary default to the user's intent line so the
// spec.yaml front door has *something* useful instead of just name+language.
function specSeed(
  projectName: string,
  language: string,
  metadata?: SpecSeedMetadata,
): string {
  const projectLines = [
    `  name: ${projectName}`,
    `  language: ${language}`,
  ];
  if (metadata?.description) {
    projectLines.push(`  description: ${quoted(metadata.description)}`);
  }
  projectLines.push(`  version: ${quoted(metadata?.version ?? '0.0.1')}`);
  if (metadata?.repository) {
    projectLines.push(`  repository: ${quoted(metadata.repository)}`);
  }
  if (metadata?.intent_summary) {
    projectLines.push(`  intent_summary: ${quoted(metadata.intent_summary)}`);
  }
  if (metadata?.ai_hints && hasAnyAiHint(metadata.ai_hints)) {
    projectLines.push('  ai_hints:');
    const h = metadata.ai_hints;
    if (h.preferred_persona) {
      projectLines.push(`    preferred_persona: ${h.preferred_persona}`);
    }
    // token_budget_per_session: DEPRECATED 0.6.0 (F-b43066) — zero runtime
    // consumers ever existed; no longer written. The schema accepts existing
    // specs carrying it until 0.7 (deleting now would false-RED them).
    if (h.test_framework) {
      projectLines.push(`    test_framework: ${h.test_framework}`);
    }
    if (h.primary_branch) {
      projectLines.push(`    primary_branch: ${h.primary_branch}`);
    }
    if (h.forbidden_patterns && h.forbidden_patterns.length > 0) {
      const list = h.forbidden_patterns.map((p) => quoted(p)).join(', ');
      projectLines.push(`    forbidden_patterns: [${list}]`);
    }
    if (h.preferred_patterns && h.preferred_patterns.length > 0) {
      projectLines.push('    preferred_patterns:');
      for (const triple of h.preferred_patterns) {
        projectLines.push(`      - when: ${quoted(triple.when)}`);
        projectLines.push(`        prefer: ${quoted(triple.prefer)}`);
        if (triple.over) {
          projectLines.push(`        over: ${quoted(triple.over)}`);
        }
      }
    }
  }

  return [
    '# Cladding · Tier A · SSoT — Iron Law sealed · Refreshed by: clad_create_feature / manual',
    `# ${projectName} — Cladding spec`,
    '# Features live in spec/features/<slug>-<hash>.yaml — one file per feature.',
    '# Edit shards there, run `clad sync` to validate, `clad check` to exercise',
    '# every Iron Law stage. See https://github.com/qwerfunch/ironclad for the standard.',
    '',
    'schema: "0.1"',
    '',
    'project:',
    ...projectLines,
    '',
    'features: []',
    '',
  ].join('\n');
}

function appendIfMissing(gitignorePath: string, marker: string, line: string): boolean {
  const existing = existsSync(gitignorePath) ? readFileSync(gitignorePath, 'utf8') : '';
  if (existing.includes(marker)) return false;
  const ensureNewline = existing.length > 0 && !existing.endsWith('\n') ? '\n' : '';
  writeFileSync(gitignorePath, `${existing}${ensureNewline}\n# Cladding runtime state\n${line}\n`);
  return true;
}


/** F-16746b — the authoritative gate: client hooks are per-dev bypassable
 * (--no-verify is printed in the hook body itself); CI + branch protection is
 * where enforcement is real. Scaffolds a starting-point workflow the user
 * owns afterwards; never overwrites an existing file. */
export function scaffoldCiWorkflow(cwd: string): 'created' | 'exists' {
  const path = join(cwd, '.github', 'workflows', 'cladding.yml');
  if (existsSync(path)) return 'exists';
  mkdirSync(join(cwd, '.github', 'workflows'), {recursive: true});
  writeFileSync(
    path,
    [
      '# Cladding · authoritative gate — scaffolded by `clad init --with-ci`.',
      '# Local git hooks reduce latency; THIS check (as a required status check',
      '# under branch protection) is where enforcement is real.',
      'name: cladding gate',
      'on:',
      '  push:',
      '  pull_request:',
      'jobs:',
      '  gate:',
      '    runs-on: ubuntu-latest',
      '    steps:',
      '      - uses: actions/checkout@v4',
      '        with:',
      '          fetch-depth: 0 # history-aware detectors (attestation/staleness) need more than a shallow clone',
      '      - uses: actions/setup-node@v4',
      '        with: {node-version: 22}',
      '      - run: npm ci || npm install',
      '      - run: npx --yes cladding check --tier=pre-push --strict --json',
      '',
    ].join('\n'),
    'utf8',
  );
  return 'created';
}

/** F-80d19d AC-006/AC-007 — informational host-wire notice for `clad init`.
 * Returns null when the wire state matches the running binary (no notice). */
export function hostWireNotice(lastSetup: string | null, pkgVersion: string | null): string | null {
  if (lastSetup == null) {
    return 'host channels not wired yet — run `clad setup`, restart your AI tool, then ask it to apply Cladding to this project';
  }
  if (pkgVersion && lastSetup !== pkgVersion) {
    return `this project's host wiring was set up at v${lastSetup} (current binary v${pkgVersion}) — run \`clad setup\` in this project to refresh its local runtime`;
  }
  return null;
}

/**
 * Scaffolds a cladding workspace at `cwd`. Idempotent; safe by default.
 *
 * @returns The list of created and skipped artifacts plus the detected language.
 */
export async function runInit(opts: InitOptions = {}): Promise<InitResult> {
  const cwd = opts.cwd ?? '.';
  const force = opts.force ?? false;
  const created: string[] = [];
  const skipped: string[] = [];

  // I13 (v0.3.27) — `detectToolchain` reads manifests (package.json
  // wins first), which mis-identifies polyglot repos that ship a
  // package.json for tooling but are written in Python / Go / Ruby /
  // Swift. When scan runs we also know the file-extension majority;
  // prefer that signal over the manifest guess.
  //
  // v0.3.32 — scan auto-detect. `opts.scan === false` (--no-scan)
  // skips the walker entirely; otherwise scan always runs and the
  // result decides whether conventions/architecture artifacts are
  // worth writing. `docs/project-context.md` is written regardless
  // (template when there is nothing observable).
  const detected = detectToolchain(cwd).language;
  const manifestLanguage = detected === 'unknown' ? 'typescript' : detected;
  const scanResult = opts.scan === false ? null : scanRoot({cwd, roots: opts.roots});
  const SCAN_AUTO_THRESHOLD = 3;
  const shouldWriteScanArtifacts =
    scanResult !== null &&
    (opts.scan === true || scanResult.stats.filesScanned >= SCAN_AUTO_THRESHOLD);
  const language =
    scanResult && scanResult.stats.dominantLanguage !== 'unknown' && scanResult.stats.dominantLanguage !== 'other'
      ? scanResult.stats.dominantLanguage
      : manifestLanguage;
  const projectName = opts.projectName ?? basename(resolve(cwd));
  const rawIntent = opts.intent?.trim();

  // F-5f6b45 — path-aware intent. When the positional argument looks like a
  // text-file path (.md / .txt / .yaml / .yml / .markdown) and the file exists
  // under cwd, load its contents and use them as the intent. The LLM has no
  // filesystem access; cladding must do the load before composing the prompt.
  // Anything not path-like (or a missing / non-text path) falls back to the
  // existing free-text intent behavior with a stderr warning when applicable.
  let intent = rawIntent;
  if (rawIntent && rawIntent.length > 0) {
    const resolution = loadIntentFromPathIfApplicable(rawIntent, cwd);
    if (resolution.warning) {
      process.stderr.write(`[clad init] ${resolution.warning}\n`);
    }
    if (resolution.loadedFrom) {
      process.stderr.write(`[clad init] loaded intent from ${resolution.loadedFrom}\n`);
    }
    intent = resolution.intent;
  }

  // v0.3.43 — intent-aware onboarding. When the user passes a free-text
  // intent (`clad init <description>`), run the LLM-driven onboarding
  // path that returns a domain-aware project-context body + refined
  // capabilities + architecture + a real F-001 title + product/business
  // clarifying questions. The result feeds the spec.yaml seed below and
  // the scan-artifact writes further down so the spec/docs surface is
  // intent-shaped from the first init. `--no-llm` and a missing
  // dispatcher both fall back to a deterministic variant that quotes
  // the intent verbatim.
  let onboarding: OnboardingResult | null = null;
  const dispatcher = opts.hostDispatcher ?? selectDispatcher({noLlm: opts.noLlm});
  if (intent && intent.length > 0) {
    const observed: OnboardingObserved = {
      cwdBasename: basename(resolve(cwd)),
      language,
      sourceFileCount: scanResult?.stats.filesScanned ?? 0,
      readmePresent: Boolean(scanResult?.projectContext?.readmeFirstParagraph),
      readmeFirstParagraph: scanResult?.projectContext?.readmeFirstParagraph ?? null,
      projectName,
    };
    onboarding = await interpretOnboardingWithFallback(intent, observed, dispatcher, cwd);

    // v0.3.44 (F-09d68b) — persist the onboarding session so `clad clarify`
    // can drive the Q&A loop without re-running the full intent prompt.
    // The state file lives at `.cladding/onboarding/state.yaml` and is
    // marked `status: done` once every question is answered.
    const initialState: OnboardingState = {
      intent,
      language,
      projectName,
      mode: onboarding.mode,
      startedAt: new Date().toISOString(),
      status: onboarding.clarifyingQuestions.length === 0 ? 'done' : 'active',
      qa: onboarding.clarifyingQuestions.map((question) => ({question, answer: null})),
    };
    saveState(cwd, initialState);

    // v0.4.1 (no-vacuous-green) — announce a non-firing dispatch. When the LLM
    // dispatcher does not fully fire, the spec/scenarios are DETERMINISTIC STUBS
    // (`scenarios: []`, the intent quoted verbatim) that look like a real
    // domain-aware spec but aren't. A silent fallback is dispatch-layer vacuous
    // green; make it loud so the user knows to wire a host / API key and re-run.
    // `clad doctor` surfaces the underlying sentinel-miss telemetry.
    if (onboarding.source !== 'llm') {
      if (opts.noLlm) {
        process.stderr.write(
          '[clad init] ℹ deterministic mode (--no-llm): spec/scenarios are stubs derived from ' +
            "the intent verbatim (scenarios empty). Re-run without --no-llm — or use 'clad clarify' — " +
            'for domain-aware generation.\n',
        );
      } else if (onboarding.source === 'deterministic') {
        process.stderr.write(
          '[clad init] ⚠ LLM dispatcher did not fire — spec/scenarios are deterministic stubs ' +
            '(scenarios empty, intent quoted). Wire a host (run cladding as an MCP server in your AI ' +
            "tool) or set an API key, then re-run or use 'clad clarify'. See 'clad doctor' for details.\n",
        );
      } else {
        // 'hybrid' — the dispatcher fired but some sentinels came back blank.
        process.stderr.write(
          '[clad init] ⚠ LLM dispatcher fired only partially — some spec/doc sections fell back to ' +
            "deterministic stubs. Run 'clad clarify' to complete them; see 'clad doctor' for the missed sections.\n",
        );
      }
    }
  }

  // 1. spec.yaml + F-001 sharded placeholder
  //
  // v0.3.49 (F-99c6e5): spec.yaml seed now carries `features: []` and
  // the F-001 placeholder lives at `spec/features/F-001-first.yaml`.
  // v0.4.0 (F-80d19d): removed F-90d054's `_meta.enrichment_status` marker —
  // project-scope plugin auto-activation in clad init guarantees an AI
  // session, so the lazy-enrichment scaffold is no longer needed.
  const specPath = join(cwd, 'spec.yaml');
  if (existsSync(specPath) && !force) {
    skipped.push('spec.yaml (exists)');
  } else {
    // v0.3.49 (F-3a5339) — when an intent is provided, seed the
    // project metadata fields too so spec.yaml has a meaningful
    // "front door". v0.3.57 (F-00eb1a) — onboarding.aiHints (if
    // the LLM returned PROJECT_METADATA) flows through to spec.yaml
    // so AI agents read inferred hints at session start.
    const seedMetadata: SpecSeedMetadata | undefined = intent
      ? {
          description: oneLine(intent),
          intent_summary: oneLine(intent),
          ai_hints: onboarding?.aiHints,
        }
      : undefined;
    writeFileSync(specPath, specSeed(projectName, language, seedMetadata));
    created.push('spec.yaml');
  }
  // 2. .cladding/ runtime dir
  const claddingDir = join(cwd, '.cladding');
  if (existsSync(claddingDir)) {
    skipped.push('.cladding/ (exists)');
  } else {
    mkdirSync(claddingDir, {recursive: true});
    created.push('.cladding/');
  }

  // 3. .gitignore append
  const gitignorePath = join(cwd, '.gitignore');
  const appended = appendIfMissing(gitignorePath, '.cladding/', '.cladding/');
  if (appended) {
    created.push('.gitignore (.cladding/ entry appended)');
  } else {
    skipped.push('.gitignore (.cladding/ entry already present)');
  }

  const proposals: string[] = [];

  // v0.3.35 — dispatcher is selected once at the top of runInit (see
  // intent-onboarding section above) and threaded through every
  // refinement path so a hosted environment touches the LLM at most
  // once per cycle. --no-llm / no-key / no-host all collapse to
  // deterministic for byte-stable CI output.

  // Phase 2 (v0.3.24, F-x) — Existing-project scan. When the scan
  // gate fires we walk `cwd` for code conventions, layers, and
  // representative modules, then write three artifacts (or divert
  // them to `.cladding/scan/*.proposal.*` if the authored copies
  // already exist).
  //
  // v0.3.35 — interpretScanWithFallback awaits the LLM when a
  // dispatcher is available (polished prose for docs/conventions.md
  // and richer responsibility comments for spec/architecture.yaml)
  // and collapses to deterministicInterpret on null/error so the
  // artifacts are always usable.
  if (shouldWriteScanArtifacts && scanResult) {
    const interp: InterpretedScan = await interpretScanWithFallback(scanResult, dispatcher, cwd);

    writeArtifact(cwd, 'docs/conventions.md', interp.conventionsMd, created, proposals);
    writeArtifact(cwd, 'spec/architecture.yaml', interp.architectureYaml, created, proposals);

    // v0.3.38 — README ## headings are mirrored into a first-class spec
    // artifact so downstream detectors can read the capability list
    // directly instead of re-parsing docs/project-context.md. LLM
    // refinement (when a dispatcher is available) adds `summary` +
    // `surface` per entry; deterministic mode ships id + title only.
    writeArtifact(cwd, 'spec/capabilities.yaml', interp.capabilitiesYaml, created, proposals);

    // v0.3.30 — scenarios are not auto-extracted from observed code.
    // A user journey is *intent*, not architecture, so cladding leaves
    // the directory empty at adoption time and registers scenarios
    // when the user requests features through `clad_create_feature`.
    // The README documents the policy so reviewers don't expect
    // populated YAMLs.
    writeArtifact(cwd, 'spec/scenarios/README.md', SCENARIOS_README, created, proposals);
  } else {
    // v0.3.42 — greenfield seeds. When no code has been observed yet
    // (auto-scan threshold of 3 source files not met, or `--no-scan`),
    // ship the three scan-derived artifacts as toolchain-default
    // templates so the spec/docs surface is always complete. Personas
    // can then drop the "if absent" branch from their guidance; a
    // later `clad init --scan` on a populated codebase will replace
    // these bodies via the existing `.cladding/scan/*.proposal`
    // divert mechanism in `writeArtifact`.
    //
    // v0.3.43 — when intent is provided, the onboarding pass produces
    // domain-aware capabilities + architecture bodies that replace the
    // toolchain-default seeds. `conventions.md` stays seed-based
    // because conventions are language-specific, not domain-specific.
    writeArtifact(cwd, 'docs/conventions.md', renderGreenfieldConventionsMd(language, projectName), created, proposals);
    writeArtifact(
      cwd,
      'spec/architecture.yaml',
      onboarding?.architectureYaml ?? renderGreenfieldArchitectureYaml(language),
      created,
      proposals,
    );
    writeArtifact(
      cwd,
      'spec/capabilities.yaml',
      onboarding?.capabilitiesYaml ?? renderGreenfieldCapabilitiesYaml(projectName),
      created,
      proposals,
    );
    writeArtifact(cwd, 'spec/scenarios/README.md', SCENARIOS_README, created, proposals);
  }

  // v0.3.32 — `docs/project-context.md` is the forest-level entry
  // document and ships in *every* cladding workspace regardless of
  // whether the scan artifacts were written.
  //
  // v0.3.33 — when an LLM dispatcher is available the Why / What /
  // Purpose sections are refined from observed README/docs into
  // polished prose. Greenfield + no-LLM environments still receive
  // the deterministic template; the dispatcher failure path also
  // collapses to deterministic so the file is always usable.
  //
  // v0.3.43 — when intent is provided, the onboarding pass produces a
  // richer body that captures the user's stated intent plus inferred
  // domain context. That body wins over the observed-README path.
  const projectContext = scanResult?.projectContext ?? null;
  let projectContextMd: string;
  if (onboarding) {
    projectContextMd = onboarding.projectContextMd;
  } else if (dispatcher) {
    projectContextMd = await renderProjectContextMdWithLlm(projectContext, projectName, dispatcher, cwd);
  } else {
    projectContextMd = renderProjectContextMd(projectContext, projectName);
  }
  writeArtifact(cwd, 'docs/project-context.md', projectContextMd, created, proposals);

  // v0.3.45 (F-d12edf) — onboarding scenarios. Each scenario from the
  // intent-aware onboarding lands in spec/scenarios/<slug>-<hash6>.yaml
  // so `clad_create_feature` can later bind new features to them via
  // the features[] array. Scenarios are Tier A (sealed by detectors)
  // but onboarding-time editable — see docs/ssot-model.md.
  if (onboarding && onboarding.scenarios.length > 0) {
    for (const scenario of onboarding.scenarios) {
      const hash = scenario.id.replace(/^S-/, '');
      const filename = `spec/scenarios/${scenario.slug}-${hash}.yaml`;
      const body = renderScenarioYaml(scenario);
      writeArtifact(cwd, filename, body, created, proposals);
    }
  }

  // F-90d054 — AGENTS.md is the single cross-host instruction surface.
  // Existing CLAUDE.md files belong to the user and are never created or
  // changed by onboarding; Claude Code reads AGENTS.md as well.
  // F-a4085adf (#199) — the adopter's AGENTS.md is now spec-driven: its managed
  // block is rendered from spec.yaml (test framework, branch, forbidden/preferred
  // patterns, preferred persona) + the cross-host persona→capability map, instead
  // of a static template. Marker-upsert keeps re-emission prose-preserving and
  // byte-stable, and a markerless (hand-authored) AGENTS.md is left untouched even
  // under --force, protecting a user's own file.
  const agentsResult = writeSpecDrivenAgentsMd(cwd);
  if (agentsResult === 'created') {
    created.push('AGENTS.md');
  } else if (agentsResult === 'updated') {
    created.push('AGENTS.md (managed block refreshed from spec)');
  } else if (agentsResult === 'skipped-unmanaged') {
    skipped.push('AGENTS.md (hand-authored — no clad markers, left untouched)');
  } else {
    skipped.push('AGENTS.md (managed block already current)');
  }
  // F-80d19d — friendly warning when host channels were never wired or are
  // out of sync with the current cladding binary. `clad setup` is the explicit
  // command for wiring; this is informational only and does not block init.
  const pkgVersion = getCurrentCladdingVersion();
  const wireNotice = hostWireNotice(getLastSetupVersion(cwd), pkgVersion);
  if (wireNotice) skipped.push(wireNotice);

  // Phase 2 (opt-in) — ambient enforcement via a git pre-commit hook. Off
  // unless `--with-hook` is passed: cladding never writes to `.git/` without
  // explicit consent. The hook runs `clad check --tier=pre-commit` (drift /
  // arch / secret) so spec↔code drift is blocked at commit time automatically.
  if (opts.withHook) {
    // F-16746b — one opt-in installs the full local ladder: pre-commit
    // (cheap, every commit) AND pre-push (strict tier — its first local
    // trigger). CI remains the authoritative gate; hooks reduce latency.
    for (const kind of ['pre-commit', 'pre-push'] as const) {
      const tierNote = kind === 'pre-commit' ? 'clad check --tier=pre-commit' : 'clad check --tier=pre-push --strict';
      const hook = installGitHook(kind, cwd, {version: pkgVersion ?? undefined});
      switch (hook.result) {
        case 'created':
          created.push(`.git/hooks/${kind} (${tierNote})`);
          break;
        case 'updated':
          created.push(`.git/hooks/${kind} (refreshed to current version)`);
          break;
        case 'unchanged':
          skipped.push(`.git/hooks/${kind} (already installed)`);
          break;
        case 'skipped-foreign':
          skipped.push(`.git/hooks/${kind} exists and is not cladding-authored — pass --force to overwrite`);
          break;
        case 'skipped-no-git':
          skipped.push('--with-hook: no .git directory — run `git init` first, then re-run with --with-hook');
          break;
      }
      if (hook.result === 'skipped-no-git') break; // one notice is enough
    }
  }

  if (opts.withCi) {
    const ci = scaffoldCiWorkflow(cwd);
    if (ci === 'created') {
      created.push('.github/workflows/cladding.yml (clad check --tier=pre-push --strict — the authoritative gate)');
    } else if (ci === 'exists') {
      skipped.push('.github/workflows/cladding.yml already exists — cladding never overwrites a CI workflow');
    }
  }

  // The Q&A loop may overwrite only byte-identical Cladding-generated design.
  // Capture after every initial artifact has landed so later user edits are
  // diverted for review rather than silently replaced.
  if (onboarding) {
    const state = loadState(cwd);
    if (state) saveState(cwd, {...state, artifactDigests: captureArtifactDigests(cwd)});
  }

  return {
    created,
    skipped,
    language,
    proposals: proposals.length ? proposals : undefined,
    clarifyingQuestions: onboarding?.clarifyingQuestions.length ? [...onboarding.clarifyingQuestions] : undefined,
    onboardingMode: onboarding?.mode,
    onboardingSource: onboarding?.source,
  };
}

/**
 * Renders one onboarding scenario as a YAML shard ready for
 * `spec/scenarios/<slug>-<hash>.yaml`. Schema mirrors the existing
 * sharded scenario format (`id`, `slug`, `title`, `flow`, `features`).
 * The header banner identifies the artifact as Tier A SSoT per
 * `docs/ssot-model.md`.
 */
function renderScenarioYaml(scenario: {
  readonly id: string;
  readonly slug: string;
  readonly title: string;
  readonly flow: string;
  readonly features: readonly string[];
}): string {
  const escapedTitle = scenario.title.replace(/"/g, '\\"');
  const flowLines = scenario.flow.split('\n').map((line) => `  ${line}`).join('\n');
  return [
    '# Cladding · Tier A · SSoT — onboarding output, edit-friendly · Refreshed by: clad init / clad clarify',
    `id: ${scenario.id}`,
    `slug: ${scenario.slug}`,
    `title: "${escapedTitle}"`,
    'flow: |',
    flowLines || '  (no flow described)',
    'features: []',
    '',
  ].join('\n');
}

/**
 * Writes `relPath` under `cwd`. When the target already exists the
 * payload is diverted to `.cladding/scan/<basename>.proposal.<ext>`
 * instead of overwriting authored content. Either way the resulting
 * path lands in `created` or `proposals` so the CLI handler can
 * report it.
 */
function writeArtifact(
  cwd: string,
  relPath: string,
  body: string,
  created: string[],
  proposals: string[],
): void {
  const target = join(cwd, relPath);
  if (existsSync(target)) {
    const proposal = join(cwd, '.cladding', 'scan', `${basename(relPath)}.proposal`);
    mkdirSync(dirname(proposal), {recursive: true});
    writeFileSync(proposal, body);
    proposals.push(`${relPath} → ${relPath.startsWith('docs/') || relPath.startsWith('spec/') ? '.cladding/scan/' : ''}${basename(relPath)}.proposal`);
    return;
  }
  mkdirSync(dirname(target), {recursive: true});
  writeFileSync(target, body);
  created.push(relPath);
}
