// Cladding · F7-B4 · canonical plugin persona/skill mirror census policy.
//
// This module is intentionally read-only. The build integration derives an
// operation plan here, validates every planned write against D10, then applies
// that exact plan. The assurance adapter reads the same census; there is no
// second persona, skill, or destination authority.

import {createHash} from 'node:crypto';
import {lstatSync, readFileSync, readdirSync} from 'node:fs';
import {join, relative, resolve} from 'node:path';

import {parse as parseYaml} from 'yaml';

/**
 * Lists the canonical persona inputs that every supported plugin mirrors.
 *
 * @see spec/features/persona-skill-md-cleanup-40327b.yaml AC-003
 */
export const PERSONAS = Object.freeze([
  'blind-author', 'developer', 'observability', 'orchestrator', 'planner', 'reviewer',
]);

/**
 * Lists the canonical skill inputs that every supported plugin mirrors.
 *
 * @see spec/features/persona-skill-md-cleanup-40327b.yaml AC-003
 */
export const SKILLS = Object.freeze([
  'changelog', 'check', 'checkpoint', 'clarify', 'doctor', 'init', 'oracle', 'rollback', 'route', 'serve', 'status', 'sync',
]);

const MIRROR_INPUT_PATHS = Object.freeze([
  ...PERSONAS.map((id) => `src/agents/${id}.md`),
  ...SKILLS.map((id) => `skills/${id}/SKILL.md`),
  'src/agents/README.md',
  'scripts/plugin-mirror-policy.mjs',
  'scripts/build-plugin.mjs',
  'package.json',
].sort(compare));

const MANAGED_ROOTS = Object.freeze([
  'plugins/claude-code/agents',
  'plugins/claude-code/commands',
  'plugins/claude-code/dist/agents',
  'plugins/codex/skills',
  'plugins/antigravity/skills',
  'plugins/gemini-cli/commands',
]);

