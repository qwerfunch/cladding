  'backticks and backslashes pass through unaltered.\n\n' +
  'Re-run `npm run build:plugin` after editing the source.\n';

const MIRROR_LAYOUT = Object.freeze(mirrorOutputLayout()
  .map((entry) => Object.freeze(entry))
  .sort((left, right) => compare(left.path, right.path)));
const MIRROR_OUTPUT_PATHS = Object.freeze(MIRROR_LAYOUT.map((entry) => entry.path));
const MIRROR_CLOSURE_PATHS = Object.freeze([...new Set([...MIRROR_INPUT_PATHS, ...MIRROR_OUTPUT_PATHS])].sort(compare));

/**
 * Returns canonical and policy input paths that determine mirror generation.
 *
 * @returns Sorted canonical and policy input paths.
 * @see spec/features/persona-skill-md-cleanup-40327b.yaml AC-004
 */
export function mirrorInputPaths() {
  return MIRROR_INPUT_PATHS;
}

/**
 * Returns exactly the generated paths managed by the mirror policy.
 *
 * @returns Sorted managed mirror output paths derived from the shared layout.
 * @see spec/features/persona-skill-md-cleanup-40327b.yaml AC-004
 */
export function mirrorOutputPaths() {
  return MIRROR_OUTPUT_PATHS;
}

/**
 * Returns the complete artifact closure of canonical inputs and managed outputs.
 *
 * @returns Sorted unique paths that invalidate the mirror census.
 * @see spec/features/persona-skill-md-cleanup-40327b.yaml AC-004
 */
export function mirrorClosurePaths() {
  return MIRROR_CLOSURE_PATHS;
}

/**
 * Returns the registry-owned mirror policy identity without directory inference.
 *
 * @returns An immutable manifest for the current mirror lanes and transforms.
 * @see spec/features/persona-skill-md-cleanup-40327b.yaml AC-003
 */
export function mirrorManifest() {
  return Object.freeze({
    personas: PERSONAS,
    skills: SKILLS,
    geminiCommands: Object.freeze(['init']),
    lanes: Object.freeze([
      'claude-agents', 'claude-init', 'claude-bundled-agents', 'codex-skills', 'antigravity-skills', 'gemini-init',
    ]),
    policy: 'plugin-mirror-census-v2',
  });
}

/**
 * Renders the Gemini command transform used by the census and build plan.
 *
 * @param raw - Canonical SKILL.md bytes to transform.
 * @returns Gemini TOML bytes, or `undefined` when frontmatter is invalid.
 * @see spec/features/persona-skill-md-cleanup-40327b.yaml AC-004
 */
export function renderGeminiToml(raw) {
  const split = splitFrontmatter(raw);
  const description = split?.frontmatter?.description;
  if (!split || typeof description !== 'string' || !description.trim()) return undefined;
  const body = split.body.trimStart().replace(/\s+$/, '');
  const header = `description = "${escapeTomlBasic(description.trim())}"`;
  return body.includes("'''")
    ? `${header}\nprompt = """\n${body.replace(/\\/g, '\\\\').replace(/"/g, '\\"')}\n"""\n`
    : `${header}\nprompt = '''\n${body}\n'''\n`;
}

/**
 * Performs a deterministic read-only mirror census without following unsafe paths.
 *
 * @param root - Workspace root containing canonical inputs and managed outputs.
 * @returns The sealed mirror census and its exact artifact closure addresses.
 * @see spec/features/persona-skill-md-cleanup-40327b.yaml AC-004
 */
export function derivePluginMirror(root) {
  const workspace = resolve(root);
  const issues = [];
  const canonical = new Map();

  validateCanonicalCatalog(workspace, issues);
  for (const path of MIRROR_INPUT_PATHS) {
    const bytes = readRegularFile(workspace, path, issues, 'canonical');
    if (bytes !== undefined) canonical.set(path, bytes);
  }
  for (const path of [...PERSONAS.map((id) => `src/agents/${id}.md`), ...SKILLS.map((id) => `skills/${id}/SKILL.md`)]) {
    const bytes = canonical.get(path);
    const split = bytes === undefined ? undefined : splitFrontmatter(bytes);
    if (!split || typeof split.frontmatter.description !== 'string' || !split.frontmatter.description.trim()) {
      issues.push(issue('malformed', path, 'canonical persona or skill requires a string YAML frontmatter description'));
    }
  }

  const personaIds = new Set(PERSONAS);
  for (const skill of SKILLS) {
    if (personaIds.has(skill)) issues.push(issue('collision', `plugins/codex/skills/${skill}`, 'persona and skill canonical inputs collide'));
  }
  const expected = expectedMirrorEntries(canonical, issues);

  const expectedPaths = new Set(expected.keys());
  const outputs = [];
  for (const [path, entry] of [...expected.entries()].sort(([left], [right]) => compare(left, right))) {
    const actual = readRegularFile(workspace, path, issues, 'destination', false);
    const expectedSha256 = sha256(entry.bytes);
    const actualSha256 = actual === undefined ? '<missing>' : sha256(actual);
    outputs.push(Object.freeze({
      path,
      source: entry.source,
      expected_sha256: expectedSha256,
      actual_sha256: actualSha256,
      ...(actual !== undefined && actual !== entry.bytes ? {state: 'stale'} : actual === undefined ? {state: 'missing'} : {state: 'current'}),
    }));
    if (actual === undefined && !hasIssue(issues, path, 'symlink')) issues.push(issue('missing', path, entry.source));
    if (actual !== undefined && actual !== entry.bytes) issues.push(issue('stale', path, entry.source));
  }
  const tree = managedTree(workspace, issues);
  for (const path of tree) {
    if (expectedPaths.has(path) || [...expectedPaths].some((expectedPath) => expectedPath.startsWith(`${path}/`))) continue;
    issues.push(issue('extra', path, 'unmanaged nested destination'));
  }

  const sortedExpected = [...expected.entries()].sort(([left], [right]) => compare(left, right))
    .map(([path, entry]) => Object.freeze({path, bytes: entry.bytes, source: entry.source, sha256: sha256(entry.bytes)}));
  const inputs = MIRROR_INPUT_PATHS.map((path) => Object.freeze({path, sha256: canonical.has(path) ? sha256(canonical.get(path)) : '<missing>'}));
  const sortedIssues = Object.freeze(uniqueIssues(issues).sort((left, right) => compare(`${left.kind}\0${left.path}\0${left.detail}`, `${right.kind}\0${right.path}\0${right.detail}`)));
  const complete = !sortedIssues.some((entry) => entry.kind === 'incomplete' || entry.kind === 'invalid' || entry.kind === 'malformed' || entry.kind === 'collision' || entry.kind === 'symlink');
  const inputSha256 = sha256(stableJson({
    manifest: mirrorManifest(),
    closure: MIRROR_CLOSURE_PATHS,
    inputs,
    expected: sortedExpected.map((entry) => ({path: entry.path, sha256: entry.sha256, source: entry.source})),
    outputs: outputs.map((entry) => ({path: entry.path, expected_sha256: entry.expected_sha256, actual_sha256: entry.actual_sha256})),
  }));
  return Object.freeze({
    manifest: mirrorManifest(),
    inputAddresses: Object.freeze(MIRROR_CLOSURE_PATHS.map((path) => `artifact:${path}`)),
    inputSha256,
    expected: Object.freeze(sortedExpected),
    outputs: Object.freeze(outputs),
    issues: sortedIssues,
    complete,
    clean: sortedIssues.length === 0,
  });
}

/**
 * Produces the exact writes and deletes a D10-validated build may apply.
 *
 * @param census - Complete read-only census that defines the operation preimage.
 * @returns Sorted write and delete operations, or none for an incomplete census.
 * @see spec/features/persona-skill-md-cleanup-40327b.yaml AC-004
 */
export function mirrorOperationPlan(census) {
  if (!census.complete) return Object.freeze([]);
  const writes = census.expected
    .filter((entry) => census.outputs.find((output) => output.path === entry.path)?.actual_sha256 !== entry.sha256)
    .map((entry) => Object.freeze({operation: 'update', path: entry.path, bytes: entry.bytes}));
  const extras = census.issues.filter((entry) => entry.kind === 'extra').map((entry) => entry.path).sort(compare);
  const deletes = extras.filter((path) => !extras.some((other) => path.startsWith(`${other}/`)))
    .map((path) => Object.freeze({operation: 'delete', path}));
  return Object.freeze([...writes, ...deletes].sort((left, right) => compare(`${left.operation}\0${left.path}`, `${right.operation}\0${right.path}`)));
}

/** Derives the one output layout consumed by both expected bytes and closure paths. */
function mirrorOutputLayout() {
  const entries = [];
  for (const persona of PERSONAS) {
    const source = `src/agents/${persona}.md`;
    entries.push(
      {path: `plugins/claude-code/agents/${persona}.md`, source, transform: 'copy'},
      {path: `plugins/claude-code/dist/agents/${persona}.md`, source, transform: 'copy'},
      {path: `plugins/codex/skills/${persona}/SKILL.md`, source, transform: 'copy'},
      {path: `plugins/antigravity/skills/${persona}/SKILL.md`, source, transform: 'copy'},
    );
  }
  for (const skill of SKILLS) {
    const source = `skills/${skill}/SKILL.md`;
    entries.push(
      {path: `plugins/codex/skills/${skill}/SKILL.md`, source, transform: 'copy'},
      {path: `plugins/antigravity/skills/${skill}/SKILL.md`, source, transform: 'copy'},
    );
  }
  entries.push(
    {path: 'plugins/claude-code/commands/init.md', source: 'skills/init/SKILL.md', transform: 'copy'},
    {path: 'plugins/gemini-cli/commands/init.toml', source: 'skills/init/SKILL.md', transform: 'gemini'},
    {path: 'plugins/claude-code/dist/agents/README.md', source: 'src/agents/README.md', transform: 'copy'},
    {path: 'plugins/claude-code/agents/README.md', source: 'mirror policy', transform: 'literal', bytes: CLAUDE_AGENTS_README},
    {path: 'plugins/codex/skills/README.md', source: 'mirror policy', transform: 'literal', bytes: CODEX_SKILLS_README},
    {path: 'plugins/gemini-cli/commands/README.md', source: 'mirror policy', transform: 'literal', bytes: GEMINI_COMMANDS_README},
  );
  return entries;
}

/** Materializes expected bytes from the shared mirror layout and canonical input map. */
function expectedMirrorEntries(canonical, issues) {
  const expected = new Map();
  for (const entry of MIRROR_LAYOUT) {
    const source = entry.transform === 'literal' ? entry.bytes : canonical.get(entry.source);
    if (source === undefined) continue;
    const bytes = entry.transform === 'gemini' ? renderGeminiToml(source) : source;
    if (bytes === undefined) {
      issues.push(issue('malformed', entry.source, 'Gemini init requires a string frontmatter description'));
      continue;
    }
    if (expected.has(entry.path)) {
      issues.push(issue('collision', entry.path, `${expected.get(entry.path).source} and ${entry.source}`));
      continue;
    }
    expected.set(entry.path, {bytes, source: entry.source});
  }
  return expected;
}

function validateCanonicalCatalog(root, issues) {
  const agents = readDirectory(root, 'src/agents', issues, 'canonical');
  for (const entry of agents) {
    if (!entry.name.endsWith('.md') || entry.name === 'README.md') continue;
    if (entry.isSymbolicLink) issues.push(issue('symlink', `src/agents/${entry.name}`, 'canonical persona may not be a symbolic link'));
    else if (!entry.isFile) issues.push(issue('invalid', `src/agents/${entry.name}`, 'canonical persona must be a regular file'));
    else if (!PERSONAS.includes(entry.name.replace(/\.md$/, ''))) issues.push(issue('invalid', `src/agents/${entry.name}`, 'unregistered persona input'));
  }
  const skills = readDirectory(root, 'skills', issues, 'canonical');
  for (const entry of skills) {
    if (entry.isSymbolicLink) {
      issues.push(issue('symlink', `skills/${entry.name}`, 'canonical skill may not be a symbolic link'));
      continue;
    }
    if (!entry.isDirectory) {
      issues.push(issue('invalid', `skills/${entry.name}`, 'canonical skill must be a directory'));
      continue;
    }
    if (PERSONAS.includes(entry.name)) issues.push(issue('collision', `plugins/codex/skills/${entry.name}`, 'persona and skill canonical inputs collide'));
    else if (!SKILLS.includes(entry.name)) issues.push(issue('invalid', `skills/${entry.name}`, 'unregistered skill input'));
  }
}

function managedTree(root, issues) {
  const paths = [];
  for (const managedRoot of MANAGED_ROOTS) walkManaged(root, managedRoot, issues, paths);
  return paths.sort(compare);
}

function walkManaged(root, path, issues, paths) {
  const entries = readDirectory(root, path, issues, 'destination', false);
  for (const entry of entries) {
    const child = `${path}/${entry.name}`;
    paths.push(child);
    if (entry.isSymbolicLink) issues.push(issue('symlink', child, 'managed destination may not be a symbolic link'));
    else if (entry.isDirectory) walkManaged(root, child, issues, paths);
  }
}

function readDirectory(root, path, issues, role, required = true) {
  const checked = safePath(root, path, issues, role);
  if (checked === undefined) {
    if (required) issues.push(issue('incomplete', path, `missing or unsafe ${role} directory`));
    return [];
  }
  if (!checked.stat.isDirectory()) {
    issues.push(issue('invalid', path, `${role} path is not a directory`));
    return [];
  }
  try {
    return readdirSync(checked.absolute, {withFileTypes: true}).sort((left, right) => compare(left.name, right.name)).map((entry) => ({
      name: entry.name,
      isFile: entry.isFile(),
      isDirectory: entry.isDirectory(),
      isSymbolicLink: entry.isSymbolicLink(),
    }));
  } catch {
    issues.push(issue('invalid', path, `${role} directory disappeared during census`));
    return [];
  }
}

function readRegularFile(root, path, issues, role, required = true) {
  const checked = safePath(root, path, issues, role);
  if (checked === undefined) {
    if (required) issues.push(issue('incomplete', path, `missing or unsafe ${role} input`));
    return undefined;
  }
  if (!checked.stat.isFile()) {
    issues.push(issue('invalid', path, `${role} path is not a regular file`));
    return undefined;
  }
  try {
    return readFileSync(checked.absolute, 'utf8');
  } catch {
    issues.push(issue('invalid', path, `${role} file disappeared during census`));
    return undefined;
  }
}

function safePath(root, path, issues, role) {
  let absolute = root;
  try {
    const rootStat = lstatSync(root);
    if (rootStat.isSymbolicLink()) {
      issues.push(issue('symlink', '.', `${role} workspace root may not be a symbolic link`));
      return undefined;
    }
    if (!rootStat.isDirectory()) {
      issues.push(issue('invalid', '.', `${role} workspace root is not a directory`));
      return undefined;
    }
  } catch {
    issues.push(issue('invalid', '.', `${role} workspace root is unreadable`));
    return undefined;
  }
  for (const segment of path.split('/')) {
    absolute = join(absolute, segment);
    try {
      const stat = lstatSync(absolute);
      if (stat.isSymbolicLink()) {
        issues.push(issue('symlink', relative(root, absolute).replaceAll('\\', '/'), `${role} path may not contain a symbolic link`));
        return undefined;
      }
      if (segment !== path.split('/').at(-1) && !stat.isDirectory()) {
        issues.push(issue('invalid', relative(root, absolute).replaceAll('\\', '/'), `${role} path ancestor is not a directory`));
        return undefined;
      }
      if (segment === path.split('/').at(-1)) return {absolute, stat};
    } catch {
      return undefined;
    }
  }
  return undefined;
}

function splitFrontmatter(raw) {
  if (!raw.startsWith('---\n')) return undefined;
  const end = raw.indexOf('\n---\n', 4);
  if (end === -1) return undefined;
  try {
    const frontmatter = parseYaml(raw.slice(4, end));
    return frontmatter && typeof frontmatter === 'object' && !Array.isArray(frontmatter)
      ? {frontmatter, body: raw.slice(end + 5)}
      : undefined;
  } catch {
    return undefined;
  }
}

function escapeTomlBasic(value) {
  return value.replace(/\\/g, '\\\\').replace(/"/g, '\\"');
}

function issue(kind, path, detail) { return Object.freeze({kind, path, detail}); }
function hasIssue(issues, path, kind) { return issues.some((entry) => entry.path === path && entry.kind === kind); }
function uniqueIssues(issues) { return [...new Map(issues.map((entry) => [`${entry.kind}\0${entry.path}\0${entry.detail}`, entry])).values()]; }
function compare(left, right) { return left < right ? -1 : left > right ? 1 : 0; }
function sha256(value) { return createHash('sha256').update(value, 'utf8').digest('hex'); }
function stableJson(value) {
  if (Array.isArray(value)) return `[${value.map(stableJson).join(',')}]`;
  if (value && typeof value === 'object') return `{${Object.entries(value).sort(([left], [right]) => compare(left, right)).map(([key, child]) => `${JSON.stringify(key)}:${stableJson(child)}`).join(',')}}`;
  return JSON.stringify(value);
}
